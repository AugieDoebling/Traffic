using Game.Pathfind;
using Traffic.Components.LaneConnections;
using Unity.Entities;

namespace Traffic.Systems.Helpers
{
    /// <summary>
    /// Helpers for lane connections at roundabouts.
    ///
    /// Roundabout lanes do not run edge-to-edge: an entry lane runs from an edge lane to a lane on the ring,
    /// an exit lane runs from a lane on the ring to an edge lane. The ring lane end is owned by the node.
    ///
    /// To keep the data compatible with the rest of the mod (which identifies every lane end as edge + lane index),
    /// the ring lane end is stored as "anchor edge + flagged lane index":
    ///  - entry: source (E, lane) -> target (E, RingEntryFlag | ringLane), the ring section right after the edge E
    ///  - exit:  source (X, RingExitFlag | ringLane) -> target (X, lane), the ring section right before the edge X
    /// where ringLane is the lane byte of the path node generated by the lane system.
    /// </summary>
    public static class RoundaboutUtils
    {
        /// <summary>Lane end on the ring, target of an entry lane</summary>
        public const int RingEntryFlag = 1 << 16;
        /// <summary>Lane end on the ring, source of an exit lane</summary>
        public const int RingExitFlag = 1 << 17;
        /// <summary>
        /// The lane end is not a lane of the ring but the middle point of the bypass lane
        /// (direct lane between adjacent edges, generated when they are less than a quarter turn apart)
        /// </summary>
        public const int RingBypassFlag = 1 << 18;
        public const int RingMask = RingEntryFlag | RingExitFlag;

        public static bool IsRingBypass(int laneIndex)
        {
            return laneIndex > 0 && (laneIndex & RingBypassFlag) != 0;
        }

        public static bool IsRing(int laneIndex)
        {
            return laneIndex > 0 && (laneIndex & RingMask) != 0;
        }

        public static bool IsRingEntry(int laneIndex)
        {
            return laneIndex > 0 && (laneIndex & RingEntryFlag) != 0;
        }

        public static bool IsRingExit(int laneIndex)
        {
            return laneIndex > 0 && (laneIndex & RingExitFlag) != 0;
        }

        /// <summary>Index of the lane on the ring (lane byte of the path node)</summary>
        public static int RingLane(int laneIndex)
        {
            return laneIndex & 0xff;
        }

        public static int EncodeEntry(int pathLaneIndex, bool isBypass = false)
        {
            return (pathLaneIndex & 0xff) | RingEntryFlag | (isBypass ? RingBypassFlag : 0);
        }

        public static int EncodeExit(int pathLaneIndex, bool isBypass = false)
        {
            return (pathLaneIndex & 0xff) | RingExitFlag | (isBypass ? RingBypassFlag : 0);
        }

        public static bool IsRingConnector(in Connector connector)
        {
            return IsRing(connector.laneIndex);
        }

        /// <summary>
        /// Tests if the connection can be created between connectors
        /// </summary>
        /// <param name="hasRing">intersection contains ring connectors (roundabout)</param>
        public static bool IsValidPair(in Connector source, in Connector target, bool hasRing)
        {
            bool sourceOnRing = IsRing(source.laneIndex);
            bool targetOnRing = IsRing(target.laneIndex);
            if (!hasRing)
            {
                return !sourceOnRing && !targetOnRing;
            }
            if (sourceOnRing == targetOnRing)
            {
                // edge-to-edge connection is not possible at the roundabout (ring-to-ring is not supported)
                return false;
            }
            if (source.edge != target.edge)
            {
                return false;
            }
            return sourceOnRing ? IsRingExit(source.laneIndex) : IsRingEntry(target.laneIndex);
        }

        public static bool IsOwnedBy(PathNode pathNode, Entity owner)
        {
            return pathNode.OwnerEquals(new PathNode(owner, 0));
        }
    }
}
